package main

import "testing"

// The generated-file marker of a stub (gaddoc.GeneratedHeader) is not shown in
// the documented source; any other leading comment is.
func TestExampleSourceDropsGeneratedHeader(t *testing.T) {
	src := "// Code generated by gaddoc api; DO NOT EDIT.\n\n/***\nM.\n***/\n\nx := 1\n"
	if got := exampleSource([]byte(src)); got != "x := 1\n" {
		t.Fatalf("got %q", got)
	}
	if got := exampleSource([]byte("// a note\n\nx := 1\n")); got != "// a note\n\nx := 1\n" {
		t.Fatalf("kept comment: %q", got)
	}
}
