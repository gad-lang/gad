// Command gen regenerates astio/register_gen.go: the list of built-in and gadx
// AST node types auto-registered for import. It scans parser/node and gadx/node
// for exported types that carry a node method (WriteCode or Pos) — i.e. AST
// nodes — and emits a Register call for each. Run via `go generate ./astio`.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strings"
)

func main() {
	nodeTypes := scan("../parser/node")
	gadxTypes := scan("../gadx/node")

	var b bytes.Buffer
	b.WriteString("package astio\n\n")
	b.WriteString("// Code generated by astio/internal/gen; DO NOT EDIT.\n\n")
	b.WriteString("import (\n")
	b.WriteString("\t\"github.com/gad-lang/gad/parser/ast\"\n\n")
	b.WriteString("\tgadxnode \"github.com/gad-lang/gad/gadx/node\"\n")
	b.WriteString("\tnode \"github.com/gad-lang/gad/parser/node\"\n")
	b.WriteString(")\n\n")
	b.WriteString("// init auto-registers the built-in and gadx AST node types for Unmarshal;\n")
	b.WriteString("// non-node candidates (enums, slices) are skipped. Custom types use Register.\n")
	b.WriteString("func init() {\n")
	b.WriteString("\tfor _, sample := range []any{\n")
	for _, t := range nodeTypes {
		fmt.Fprintf(&b, "\t\t(*node.%s)(nil),\n", t)
	}
	for _, t := range gadxTypes {
		fmt.Fprintf(&b, "\t\t(*gadxnode.%s)(nil),\n", t)
	}
	b.WriteString("\t} {\n")
	b.WriteString("\t\tif _, ok := sample.(ast.Node); ok {\n")
	b.WriteString("\t\t\tRegister(sample)\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t}\n")
	b.WriteString("}\n")

	if err := os.WriteFile("register_gen.go", b.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	fmt.Printf("register_gen.go: %d node + %d gadx types\n", len(nodeTypes), len(gadxTypes))
}

// scan returns the exported type names in dir that have a node method (WriteCode
// or Pos) — the AST nodes.
func scan(dir string) []string {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(fi os.FileInfo) bool {
		return !strings.HasSuffix(fi.Name(), "_test.go")
	}, 0)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen: parse", dir, err)
		os.Exit(1)
	}
	set := map[string]bool{}
	for _, pkg := range pkgs {
		for _, file := range pkg.Files {
			for _, decl := range file.Decls {
				fn, ok := decl.(*ast.FuncDecl)
				if !ok || fn.Recv == nil || len(fn.Recv.List) == 0 {
					continue
				}
				if fn.Name.Name != "WriteCode" && fn.Name.Name != "Pos" {
					continue
				}
				if name := recvType(fn.Recv.List[0].Type); name != "" && ast.IsExported(name) {
					set[name] = true
				}
			}
		}
	}
	out := make([]string, 0, len(set))
	for t := range set {
		out = append(out, t)
	}
	sort.Strings(out)
	return out
}

// recvType returns the receiver's type name (dereferencing a pointer receiver).
func recvType(e ast.Expr) string {
	if star, ok := e.(*ast.StarExpr); ok {
		e = star.X
	}
	if id, ok := e.(*ast.Ident); ok {
		return id.Name
	}
	return ""
}
